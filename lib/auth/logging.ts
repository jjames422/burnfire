const AUTH_FAILURE_MESSAGES = {
  CODE_DELIVERY_FAILED: "[auth] CODE_DELIVERY_FAILED",
  CODE_REQUEST_FAILED: "[auth] CODE_REQUEST_FAILED",
  CODE_VERIFICATION_FAILED: "[auth] CODE_VERIFICATION_FAILED",
  LINK_DELIVERY_FAILED: "[auth] LINK_DELIVERY_FAILED",
  LINK_REQUEST_FAILED: "[auth] LINK_REQUEST_FAILED",
  LINK_CONSUMPTION_FAILED: "[auth] LINK_CONSUMPTION_FAILED",
  SESSION_LOAD_FAILED: "[auth] SESSION_LOAD_FAILED",
  SIGNOUT_FAILED: "[auth] SIGNOUT_FAILED",
  PASSKEY_VERIFICATION_FAILED: "[auth] PASSKEY_VERIFICATION_FAILED",
  PASSKEY_LIST_FAILED: "[auth] PASSKEY_LIST_FAILED",
  PASSKEY_DELETE_FAILED: "[auth] PASSKEY_DELETE_FAILED",
} as const;

/** Deliberately accepts no error payload: provider errors can contain credentials. */
export function logAuthFailure(code: keyof typeof AUTH_FAILURE_MESSAGES): void {
  console.error(Object.hasOwn(AUTH_FAILURE_MESSAGES, code)
    ? AUTH_FAILURE_MESSAGES[code]
    : "[auth] AUTH_OPERATION_FAILED");
}
