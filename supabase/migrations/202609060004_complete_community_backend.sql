  insert into public.audit_events(actor_id,alliance,action,target_type,target_id)
  values (auth.uid(),invitation.alliance,'invitation.revoked','invitation',invitation.id::text);
end;
$$;
grant execute on function public.revoke_alliance_invitation(uuid) to authenticated;

create or replace function public.manage_alliance_member(
  p_user_id uuid, p_game_rank game_rank, p_alliance_title alliance_title,
  p_permission_role permission_role
) returns public.alliance_members
language plpgsql security definer set search_path = public, pg_temp as $$
declare member public.alliance_members;
begin
  select * into member from public.alliance_members where user_id = p_user_id for update;
  if not found then raise exception 'Alliance member not found'; end if;
  if not (public.is_platform_admin() or public.my_role(member.alliance) = 'admin')
  then raise exception 'Alliance administrator required'; end if;
  if p_user_id = auth.uid() and (p_permission_role <> member.permission_role or p_game_rank <> member.game_rank)
  then raise exception 'Administrators cannot change their own authority'; end if;
  update public.alliance_members set game_rank=p_game_rank, alliance_title=p_alliance_title,
    permission_role=p_permission_role, verified_at=now(), verified_by=auth.uid()
    where user_id=p_user_id returning * into member;
  update public.profiles set permission_role=p_permission_role where id=p_user_id;
  insert into public.audit_events(actor_id,alliance,action,target_type,target_id,details)
  values (auth.uid(),member.alliance,'membership.updated','profile',p_user_id::text,
    jsonb_build_object('rank',p_game_rank,'title',p_alliance_title,'role',p_permission_role));
  insert into public.notifications(user_id,kind,title,body,data)
  values (p_user_id,'membership_updated','Alliance standing updated','Your alliance rank or access was changed.',
    jsonb_build_object('alliance',member.alliance));
  return member;
end;
$$;
grant execute on function public.manage_alliance_member(uuid,game_rank,alliance_title,permission_role) to authenticated;

create or replace function public.transfer_alliance_leadership(p_new_leader_id uuid)
returns void language plpgsql security definer set search_path=public,pg_temp as $$
declare old_leader public.alliance_members; declare new_leader public.alliance_members;
begin
  select * into old_leader from public.alliance_members where user_id=auth.uid() and game_rank='r5' for update;
  if not found and not public.is_platform_admin() then raise exception 'Alliance leader required'; end if;
  if public.is_platform_admin() and old_leader.user_id is null then
    select * into new_leader from public.alliance_members where user_id=p_new_leader_id for update;
    select * into old_leader from public.alliance_members where alliance=new_leader.alliance and game_rank='r5' for update;
  else
    select * into new_leader from public.alliance_members
      where user_id=p_new_leader_id and alliance=old_leader.alliance for update;
  end if;
  if new_leader.user_id is null then raise exception 'New leader must belong to the alliance'; end if;
  update public.alliance_members set game_rank='r4',alliance_title=null,permission_role='officer',
    verified_at=now(),verified_by=auth.uid() where user_id=old_leader.user_id;
  update public.alliance_members set game_rank='r5',alliance_title='alliance_leader',permission_role='admin',
    verified_at=now(),verified_by=auth.uid() where user_id=new_leader.user_id;
  update public.profiles set permission_role='officer' where id=old_leader.user_id;
  update public.profiles set permission_role='admin' where id=new_leader.user_id;
  insert into public.audit_events(actor_id,alliance,action,target_type,target_id,details)
  values(auth.uid(),new_leader.alliance,'leadership.transferred','profile',new_leader.user_id::text,
    jsonb_build_object('previous_leader',old_leader.user_id));
end;
$$;
grant execute on function public.transfer_alliance_leadership(uuid) to authenticated;

