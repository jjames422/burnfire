create or replace function public.invite_to_alliance(
  p_alliance text, p_invitee_id uuid, p_game_rank game_rank default 'r1',
  p_alliance_title alliance_title default null,
  p_permission_role permission_role default 'member'
) returns public.alliance_invitations
language plpgsql security definer set search_path = public, pg_temp as $$
declare result public.alliance_invitations;
declare actor_role permission_role;
begin
  if not public.can_manage_alliance(p_alliance) then raise exception 'Alliance manager required'; end if;
  select public.my_role(p_alliance) into actor_role;
  if not public.is_platform_admin() and actor_role = 'officer'
     and (p_game_rank in ('r4','r5') or p_permission_role <> 'member' or p_alliance_title is not null)
  then raise exception 'Only an alliance administrator may grant officer or leader standing'; end if;
  if p_invitee_id = auth.uid() then raise exception 'You cannot invite yourself'; end if;
  if exists (select 1 from public.alliance_members where user_id = p_invitee_id)
  then raise exception 'This player already belongs to an alliance'; end if;
  update public.alliance_invitations set status = 'expired', responded_at = now()
    where invitee_id = p_invitee_id and status = 'pending' and expires_at <= now();
  insert into public.alliance_invitations
    (alliance, invitee_id, invited_by, game_rank, alliance_title, permission_role)
  values (p_alliance, p_invitee_id, auth.uid(), p_game_rank, p_alliance_title, p_permission_role)
  returning * into result;
  insert into public.notifications(user_id, kind, title, body, data)
  select p_invitee_id, 'alliance_invitation', 'Alliance invitation',
    'You were invited to join ' || a.name || '.', jsonb_build_object('invitation_id', result.id)
  from public.alliances a where a.slug = p_alliance;
  insert into public.audit_events(actor_id, alliance, action, target_type, target_id, details)
  values (auth.uid(), p_alliance, 'invitation.created', 'profile', p_invitee_id::text,
    jsonb_build_object('rank', p_game_rank, 'title', p_alliance_title, 'role', p_permission_role));
  return result;
end;
$$;
grant execute on function public.invite_to_alliance(text,uuid,game_rank,alliance_title,permission_role) to authenticated;

create or replace function public.respond_to_alliance_invitation(p_invitation_id uuid, p_accept boolean)
returns public.alliance_invitations
language plpgsql security definer set search_path = public, pg_temp as $$
declare invitation public.alliance_invitations;
begin
  select * into invitation from public.alliance_invitations
    where id = p_invitation_id and invitee_id = auth.uid() and status = 'pending' for update;
  if not found then raise exception 'Pending invitation not found'; end if;
  if invitation.expires_at <= now() then
    update public.alliance_invitations set status = 'expired', responded_at = now() where id = invitation.id
    returning * into invitation;
    return invitation;
  end if;
  if p_accept then
    insert into public.alliance_members
      (alliance,user_id,permission_role,game_rank,alliance_title,verified_at,verified_by)
    values (invitation.alliance,auth.uid(),invitation.permission_role,invitation.game_rank,
      invitation.alliance_title,now(),invitation.invited_by);
    update public.profiles set alliance = invitation.alliance,
      permission_role = invitation.permission_role where id = auth.uid();
  end if;
  update public.alliance_invitations set status = case when p_accept then 'accepted' else 'declined' end,
    responded_at = now() where id = invitation.id returning * into invitation;
  insert into public.notifications(user_id,kind,title,body,data)
  values (invitation.invited_by,'invitation_response','Invitation response',
    case when p_accept then 'Your alliance invitation was accepted.' else 'Your alliance invitation was declined.' end,
    jsonb_build_object('invitation_id', invitation.id));
  insert into public.audit_events(actor_id,alliance,action,target_type,target_id)
  values (auth.uid(),invitation.alliance,case when p_accept then 'invitation.accepted' else 'invitation.declined' end,
    'profile',auth.uid()::text);
  return invitation;
end;
$$;
grant execute on function public.respond_to_alliance_invitation(uuid,boolean) to authenticated;

create or replace function public.revoke_alliance_invitation(p_invitation_id uuid)
