create or replace function public.create_alliance(p_slug text,p_code text,p_name text,p_kingdom_number integer)
returns public.alliances language plpgsql security definer set search_path=public,pg_temp as $$
declare result public.alliances;
begin
  if not public.is_platform_admin() then raise exception 'Platform administrator required'; end if;
  if trim(p_slug) !~ '^[a-z0-9-]{2,40}$' then raise exception 'Invalid alliance slug'; end if;
  if upper(trim(p_code)) !~ '^[A-Z0-9]{3}$' then raise exception 'Alliance code must be three letters or numbers'; end if;
  if char_length(trim(p_name)) not between 2 and 80 then raise exception 'Invalid alliance name'; end if;
  insert into public.alliances(slug,code,name,kingdom_number)
  values(trim(p_slug),upper(trim(p_code)),trim(p_name),p_kingdom_number) returning * into result;
  insert into public.audit_events(actor_id,alliance,action,target_type,target_id)
  values(auth.uid(),result.slug,'alliance.created','alliance',result.slug);
  return result;
end;
$$;
grant execute on function public.create_alliance(text,text,text,integer) to authenticated;

