create or replace function public.enforce_interaction_rate()
returns trigger language plpgsql security definer set search_path=public,pg_temp as $$
declare action_name text:=tg_argv[0]; declare maximum int:=tg_argv[1]::int;
declare window_size interval:=tg_argv[2]::interval;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  if (select count(*) from public.interaction_events where user_id=auth.uid() and action=action_name
      and created_at>now()-window_size)>=maximum then raise exception 'Rate limit exceeded'; end if;
  insert into public.interaction_events(user_id,action) values(auth.uid(),action_name);
  return new;
end;
$$;
