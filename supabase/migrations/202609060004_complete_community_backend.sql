-- Invitations are addressed to an existing magic-link profile. Officers may
-- invite R1-R3; alliance admins may also assign R4/R5 and unique titles.
create table if not exists public.alliance_invitations (
  id uuid primary key default gen_random_uuid(),
  alliance text not null references public.alliances(slug) on delete cascade,
  invitee_id uuid not null references public.profiles(id) on delete cascade,
  invited_by uuid not null references auth.users(id) on delete cascade,
  game_rank game_rank not null default 'r1',
  alliance_title alliance_title,
  permission_role permission_role not null default 'member',
  status text not null default 'pending'
    check (status in ('pending', 'accepted', 'declined', 'revoked', 'expired')),
  expires_at timestamptz not null default (now() + interval '7 days'),
  created_at timestamptz not null default now(),
  responded_at timestamptz,
  check (
    (game_rank in ('r1','r2','r3') and alliance_title is null)
    or (game_rank = 'r4' and (alliance_title is null or alliance_title in ('diplomat','recruiter','goddess','god_of_war')))
    or (game_rank = 'r5' and alliance_title = 'alliance_leader')
  )
);
create unique index if not exists alliance_invitations_one_pending_per_user
  on public.alliance_invitations(invitee_id) where status = 'pending';
create index if not exists alliance_invitations_alliance_idx
  on public.alliance_invitations(alliance, created_at desc);
alter table public.alliance_invitations enable row level security;
grant select on public.alliance_invitations to authenticated;
create policy "users and alliance managers read invitations"
on public.alliance_invitations for select to authenticated
using (invitee_id = auth.uid() or public.can_manage_alliance(alliance));

