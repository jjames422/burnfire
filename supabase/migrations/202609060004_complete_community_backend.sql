create or replace function public.moderate_content(
  p_target_type text,p_target_id uuid,p_action text,p_note text default null
) returns void language plpgsql security definer set search_path=public,pg_temp as $$
begin
  if not public.is_platform_admin() then raise exception 'Platform administrator required'; end if;
  if p_target_type='comment' then
    update public.comments set status=case when p_action='approve' then 'approved' else 'rejected' end where id=p_target_id;
  elsif p_target_type='message' then
    update public.messages set deleted_at=case when p_action='approve' then null else now() end where id=p_target_id;
  elsif p_target_type='fan_art' then
    update public.fan_art set status=case when p_action='approve' then 'approved' else 'rejected' end,
      moderation_note=p_note,moderated_by=auth.uid(),moderated_at=now() where id=p_target_id;
  else raise exception 'Unsupported target type'; end if;
  if not found then raise exception 'Content not found'; end if;
  update public.content_reports set status='resolved',resolved_by=auth.uid(),resolved_at=now()
    where target_type=p_target_type and target_id=p_target_id and status='open';
  insert into public.audit_events(actor_id,action,target_type,target_id,details)
  values(auth.uid(),'moderation.'||p_action,p_target_type,p_target_id::text,jsonb_build_object('note',p_note));
end;
$$;
grant execute on function public.moderate_content(text,uuid,text,text) to authenticated;

