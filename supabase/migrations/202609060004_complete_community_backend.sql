-- Approved comments remain public, but authenticated users do not see either side of a block.
create or replace function public.get_guide_comments(p_alliance text,p_guide_slug text)
returns table(id uuid,body text,identity_label text,created_at timestamptz)
language sql stable security definer set search_path=public,pg_temp as $$
  select c.id,c.body,
    case when c.author_id is null then c.author_name || case when c.author_rank is null then '' else ' · '||c.author_rank end
         else coalesce(public.format_member_identity(c.author_id),'Former member') end,c.created_at
  from public.comments c where c.status='approved' and c.alliance=p_alliance and c.guide_slug=p_guide_slug
    and (auth.uid() is null or c.author_id is null or not public.is_blocked_pair(c.author_id))
  order by c.created_at desc;
$$;

-- Small health contract for deploy checks; no user data is exposed.
create or replace function public.backend_health()
returns jsonb language sql stable security definer set search_path=public,pg_temp as $$
  select jsonb_build_object(
    'status','ok','alliance_count',(select count(*) from public.alliances),
    'pending_invitations',(select count(*) from public.alliance_invitations where status='pending' and expires_at>now()),
    'open_reports',(select count(*) from public.content_reports where status='open'),
    'checked_at',now()
  ) where public.is_platform_admin();
$$;
revoke execute on function public.backend_health() from public,anon;
grant execute on function public.backend_health() to authenticated;

